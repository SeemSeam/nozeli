import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {Controller} from '../src/agents/managed/controller.mjs';
import {createFrontdeskDocuments} from '../src/agents/managed/frontdesk-documents.mjs';
import {DesktopHost} from '../src/main/host.mjs';
import {FileChanges} from '../src/domain/file-changes.mjs';

test('Worker live registered and external host edits retain agent2 Work authorship',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'nozeli-worker-authorship-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const sourceRoot=path.join(root,'source'),registeredRoot=path.join(root,'registered'),externalRoot=path.join(root,'external');
 for(const dir of [sourceRoot,registeredRoot,externalRoot])await fs.mkdir(dir);
 const host=new DesktopHost(path.join(root,'profile'));
 const source=(await host.pick(sourceRoot)).project,target=(await host.pick(registeredRoot)).project;
 for(const dir of [registeredRoot,externalRoot])await fs.writeFile(path.join(dir,'notes.txt'),'baseline text');
 const work={id:'original-worker',name:'Original Worker',status:'running',revision:3,binding:{provider:'omp'}};
 const job={id:'worker-job',target:work.id,context:{}},session={threadId:'worker-thread',viewOwnerId:'worker-view'};
 const state={workspaceId:source.id,bindings:{worker:{provider:'omp'}},jobs:[job],works:[work]};
 const c=Object.create(Controller.prototype);
 c.projectId=source.id;c.store={state,storage:host.storage,find:id=>{assert.equal(id,work.id);return work;},mutate:async fn=>fn()};
 c.sessions=new Map([[work.id,session]]);c.current=new Map([[work.id,job]]);c.changed=()=>{};c.emit=()=>{};
 c.frontdeskDocuments=createFrontdeskDocuments({host,projectId:source.id,sync:async()=>()=>{}});
 c.resolveRegisteredProject=async candidate=>candidate===target.id||candidate===registeredRoot?{projectId:target.id,root:registeredRoot}:{projectId:null,root:await fs.realpath(candidate),external:true};
 const call=async(op,args,callId)=>{const result=await c.frontdeskOperation(job,{arguments:args,callId},op);assert.equal(result.ok,true,JSON.stringify(result));return result.value;};
 const assertActor=actor=>{assert.equal(actor.id,'nozeli:worker:'+work.id);assert.equal(actor.kind,'agent2');assert.equal(actor.mark,'W');assert.equal(actor.workId,work.id);assert.equal(actor.revision,3);assert.equal(actor.role,'worker');assert.equal(actor.sessionId,session.threadId);assert.equal(actor.sessionInstance,session.viewOwnerId);assert.equal(actor.sourceJobId,job.id);};
 const registeredRead=await call('read',{projectPath:registeredRoot,relPath:'notes.txt'},'registered-read');
 await call('apply',{readHandle:registeredRead.readHandle,replacements:[{oldText:'baseline',newText:'registered Worker'}]},'registered-write');
 assert.equal(await fs.readFile(path.join(registeredRoot,'notes.txt'),'utf8'),'registered Worker text');
 const history=await new FileChanges({root:registeredRoot,storage:host.storage,projectId:target.id}).read('notes.txt');
 assertActor(history.events.at(-1).actor);
 const externalRead=await call('read',{projectPath:externalRoot,relPath:'notes.txt'},'external-read');
 await call('apply',{readHandle:externalRead.readHandle,replacements:[{oldText:'baseline',newText:'external Worker'}]},'external-write');
 assert.equal(await fs.readFile(path.join(externalRoot,'notes.txt'),'utf8'),'external Worker text');
 const operationId=createHash('sha256').update(state.workspaceId+job.id+'external-write').digest('hex');
 const receipt=await host.storage.getLocal(source.id,'managed:external-document:'+operationId);
 assert.equal(receipt.status,'completed');assertActor(receipt.value.actor);
 assert.equal((await host.recent()).projects.some(project=>project.rootDisplay===externalRoot),false);
 assert.deepEqual(await fs.readdir(externalRoot),['notes.txt']);
});
