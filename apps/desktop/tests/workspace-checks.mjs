import { contentToolForPage } from './native-content-tools.fixture.mjs';
import assert from 'node:assert/strict';

export async function checkWorkspace({ page, projectId, record }) {
  const click = id => page.evaluate(id => document.getElementById(id).click(), id);
  const snapshot = async () => page.evaluate(async id => (await window.nozeli.invoke('state.read', { projectId: id })).value.state?.workspace, projectId);
  await page.type('#composer', '项目草稿：保留这段问题');
  await page.waitForFunction(() => document.querySelector('#compose-status').textContent.includes('已保存'));
  record('project composer persists unsent draft over real IPC', (await snapshot()).draft === '项目草稿：保留这段问题');
  record('AI send remains unavailable while local draft is editable', await page.evaluate(() => !document.querySelector('#composer').disabled && document.querySelector('#send-message').disabled));
  const originalWidth = await page.$eval('#reader', n => n.clientWidth);
  await click('file-toggle'); await click('toggle-sidebar');
  record('both collapsed rails release reading width', await page.$eval('#reader', (n, width) => n.clientWidth > width + 300, originalWidth));
  await click('file-toggle'); await click('toggle-sidebar');
  for (const dock of ['top','right','left','bottom']) {
    await page.evaluate(() => { document.querySelector('#chat-layout').open = true; });
    const probe = await page.evaluate(dock => {
      const button = document.querySelector('button[data-dock="' + dock + '"]');
      button.scrollIntoView({ block: 'center', inline: 'center' });
      const rect = button.getBoundingClientRect();
      const hit = document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2);
      return { x: rect.x + rect.width / 2, y: rect.y + rect.height / 2, hit: hit === button || button.contains(hit), tag: hit?.id || hit?.className || hit?.tagName };
    }, dock);
    record('dock ' + dock + ' menu is under the pointer', probe.hit, JSON.stringify(probe));
    await page.mouse.click(probe.x, probe.y);
    const result = await page.evaluate(dock => {
      const a = document.querySelector('#documents').getBoundingClientRect(), b = document.querySelector('#conversation-panel').getBoundingClientRect();
      return { dock: document.querySelector('#work-surface').dataset.dock, overlap: Math.min(a.right,b.right)-Math.max(a.left,b.left)>1 && Math.min(a.bottom,b.bottom)-Math.max(a.top,b.top)>1, draft: document.querySelector('#composer').value, expected: dock };
    }, dock);
    record('dock ' + dock + ' allocates non-overlapping reading space and preserves draft', result.dock === dock && !result.overlap && result.draft.includes('保留这段问题'), JSON.stringify(result));
  }
  await click('float-conversation');
  const beforeDrag = await page.$eval('#conversation-panel', node => node.getBoundingClientRect().toJSON());
  await page.mouse.move(beforeDrag.x + 24, beforeDrag.y + 12);
  await page.mouse.down();
  await page.mouse.move(beforeDrag.x + 80, beforeDrag.y + 40, { steps: 6 });
  await page.mouse.up();
  record('floating chat moves with a real pointer drag', await page.$eval('#conversation-panel', (node, x) => node.getBoundingClientRect().left > x + 20, beforeDrag.x));
  await page.evaluate(name => window.nozeli.invoke('session.capture', { name }), 'float-chat');
  await page.focus('#conversation-head');
  const previousX = await page.$eval('#conversation-panel', n => n.getBoundingClientRect().left);
  await page.keyboard.press('ArrowRight');
  record('floating panel supports keyboard movement', await page.$eval('#conversation-panel', (n,x) => n.getBoundingClientRect().left > x, previousX));
  await click('chat-minimize');
  record('minimize retains composer and exposes launcher', await page.evaluate(() => document.querySelector('#conversation-panel').hidden && !document.querySelector('#conversation-launcher').hidden && document.querySelector('#composer').value.includes('保留')));
  await click('conversation-launcher');
  await click('float-conversation');
  await page.focus('#chat-resize');
  const previousHeight = await page.$eval('#conversation-panel', n => n.clientHeight);
  await page.keyboard.press('ArrowUp');
  record('chat separator resizes with keyboard', await page.$eval('#conversation-panel', (n,height) => n.clientHeight > height, previousHeight));
  await click('toggle-focus');
  record('Zen fills the workspace without removing its exit', await page.evaluate(() => document.querySelector('#app').classList.contains('focus-mode') && document.querySelector('#toggle-focus').getAttribute('aria-pressed') === 'true'));
  await click('toggle-focus');
  await page.type('#file-filter', '第二份');
  record('file filter hides unrelated files', await page.$eval('#file-tree button[data-path="中文 目录/笔记.md"]', n => n.hidden));
  await page.$eval('#file-filter', n => { n.value=''; n.dispatchEvent(new Event('input')); });
  await contentToolForPage(page, ['history', 'compareFile']); await page.waitForSelector('#beside-dialog[open]');
  await page.select('#beside-file', '中文 目录/第二份.md');
  await page.$eval('#beside-form', n => n.requestSubmit());
  await page.waitForSelector('#secondary-text .cm-content');
  record('real secondary text is read-only and primary PDF stays open', await page.evaluate(() => document.querySelector('#secondary-text .cm-content').textContent.includes('第二份正文') && document.querySelector('#secondary-text .cm-content').getAttribute('contenteditable') === 'false' && !!document.querySelector('#pdf-host canvas')));
  await page.evaluate(name => window.nozeli.invoke('session.capture', { name }), 'dual-readonly');
  await page.focus('#pane-divider'); await page.keyboard.press('ArrowRight');
  record('dual divider adjusts with keyboard', await page.$eval('#documents', n => n.style.getPropertyValue('--split') === '55%'));
  await click('secondary-close');
  await page.waitForFunction(() => document.querySelector('#secondary-pane').hidden);
  record('closing secondary retains primary', await page.$eval('#pdf-host', n => !n.hidden));
  const width = await page.$eval('#pdf-host canvas', n => n.width);
  await click('pdf-zoom-in');
  await page.waitForFunction(width => document.querySelector('#pdf-host canvas').width > width, {}, width);
  record('PDF zoom changes the real rendered canvas', true);
  await click('pdf-fit');
  await page.waitForFunction(() => !!document.querySelector('#pdf-host .textLayer span'));
  await click('pdf-outline-toggle');
  await page.waitForFunction(() => document.querySelector('#pdf-outline').textContent.length > 0);
  record('PDF outline uses document entries or honest empty state', await page.$eval('#pdf-outline', n => !n.hidden));
  await click('pdf-outline-toggle'); await click('pdf-search-toggle');
  await page.type('#pdf-query', 'Nozeli');
  await page.$eval('#pdf-search', n => n.requestSubmit());
  await page.waitForFunction(() => document.querySelector('#pdf-search-status').textContent.includes('页匹配'));
  record('PDF search finds actual document text', true);
  await click('pdf-search-toggle');
  await page.$eval('#pdf-page', n => { n.value='1'; n.dispatchEvent(new Event('change')); });
  await page.waitForFunction(() => document.querySelector('#pdf-page').value === '1');
  const stored = await snapshot(); assert.equal(stored.draft, '项目草稿：保留这段问题');
  await page.reload();
  await page.waitForFunction(() => window.__nozeliReady && document.querySelector('#composer').value.includes('保留这段问题') && document.querySelector('#pdf-host .textLayer span'));
  record('reload restores project draft and conversation layout', await page.evaluate(() => document.querySelector('#work-surface').dataset.dock === 'bottom'));
  await click('close-subject');
  await page.waitForFunction(() => !document.querySelector('#empty').hidden);
  record('close document returns to project conversation without clearing draft', await page.$eval('#composer', n => n.value.includes('保留这段问题')));
  await page.reload();
  await page.waitForFunction(() => window.__nozeliReady && document.querySelector('#composer').value.includes('保留这段问题'));
  record('closed document remains closed on restart', await page.$eval('#empty', n => !n.hidden));
  await page.evaluate(() => document.querySelector('#file-tree button[data-path="中文 目录/样例.pdf"]').click());
  await page.waitForSelector('#pdf-host .textLayer span');
}
