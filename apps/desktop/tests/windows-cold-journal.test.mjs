const {SessionManager}=await import(pathToFileURL(path.join(integration,'node_modules/@earendil-works/pi-coding-agent/dist/core/session-manager.js')));
const native={skip:process.platform!=='win32'||process.arch!=='x64'};
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const rows=bytes=>bytes.toString('utf8').split('\n').filter(line=>line.trim()).map(line=>JSON.parse(line));
async function fixture(t){
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'nozeli cold journal 中文 ')),home=path.join(root,'owner'),agentDir=path.join(home,'config'),project=path.join(root,'project'),project2=path.join(root,'project two');
 await ensureExperimentalPrivateDirectory(root,agentDir);
 const bridge=path.resolve(import.meta.dirname,'../native/windows/build/Release/nozeli_windows_read.node');
 const env={NOZELI_PI_PRIVATE_ROOT:root,NOZELI_PI_WINDOWS_NATIVE_BRIDGE:bridge,NOZELI_PI_WINDOWS_NATIVE_SHA256:sha(await fs.readFile(bridge))},before={};
 for(const [k,v] of Object.entries(env)){before[k]=process.env[k];process.env[k]=v;}
 let directory,storage;
 t.after(async()=>{try{storage?.close();}finally{directory?.close();for(const [k,v] of Object.entries(before)){if(v===undefined)delete process.env[k];else process.env[k]=v;}await fs.rm(root,{recursive:true,force:true});}});
 directory=await prepareJournalDirectory(project,agentDir);
 storage=await createOwnerJournalStorage({agentDir});
 return {root,agentDir,project,project2,directory,storage};
}
const user=text=>({role:'user',content:[{type:'text',text}]});

test('cold journal custody keeps original outputs across create, append, /new, branch, fork and cold reopen',native,async t=>{
 const f=await fixture(t);
 const manager=SessionManager.create(f.project,f.directory.directory,undefined,f.storage);
 const sessionId=manager.getSessionId(),userText='中文 cold custody 😀';
 manager.appendMessage(user(userText));
 const file1=manager.getSessionFile();
 f.directory.verify(file1);
 const firstBytes=Buffer.from(f.storage.read(file1));
 const parsed=parseConfirmedJournal(firstBytes,sessionId);
 assert.equal(parsed.entries.length,1);
 assert.equal(parsed.entries[0].message.content[0].text,userText);
 manager.appendMessage({role:'assistant',content:[{type:'text',text:'ack'}]});
 const grown=Buffer.from(f.storage.read(file1));
 assert.ok(grown.length>firstBytes.length&&grown.subarray(0,firstBytes.length).equals(firstBytes));
 const custody=f.storage.snapshot();
 const row=custody.files.find(entry=>entry.file===file1);
 assert.ok(row&&row.byteLength===grown.length&&row.identity);
 assert.equal(custody.mechanism,'original-native-journal-writer');
 assert.equal(custody.fullRecoveryClosureQualified,false);
 await assert.rejects(fs.appendFile(file1,'external'));
 await assert.rejects(fs.writeFile(file1,'external winner'));
 assert.deepEqual(Buffer.from(f.storage.read(file1)),grown);
 manager.newSession();
 const session2=manager.getSessionId(),file2=manager.getSessionFile();
 assert.notEqual(session2,sessionId);assert.notEqual(file2,file1);
 const secondId=manager.appendMessage(user('second turn'));
 assert(Buffer.from(f.storage.read(file1)).equals(grown));
 parseConfirmedJournal(Buffer.from(f.storage.read(file2)),session2);
 const file3=manager.createBranchedSession(secondId);
 assert.ok(file3);
 const branch=parseConfirmedJournal(Buffer.from(f.storage.read(file3)),manager.getSessionId());
 assert.deepEqual(branch.entries.map(entry=>entry.id),[secondId]);
 const sourceRows=rows(grown);
 const forked=SessionManager.forkFrom(file1,f.project2,f.directory.directory,undefined,f.storage);
 const forkFile=forked.getSessionFile();
 f.directory.verify(forkFile);
 const forkRows=rows(Buffer.from(f.storage.read(forkFile)));
 assert.notEqual(forked.getSessionId(),sessionId);
 assert.equal(forkRows[0].cwd,path.resolve(f.project2));
 assert.equal(forkRows[0].parentSession,file1);
 assert.deepEqual(forkRows.slice(1),sourceRows.slice(1));
 const coldBytes=Buffer.from(f.storage.read(file1));
 f.storage.close();f.directory.close();
 assert((await fs.readFile(file1)).equals(coldBytes));
 const coldStorage=await createOwnerJournalStorage({agentDir:f.agentDir});
 const reopened=SessionManager.open(file1,undefined,f.project,coldStorage);
 assert.equal(reopened.getSessionId(),sessionId);
 reopened.appendMessage({role:'assistant',content:[{type:'text',text:'cold ack'}]});
 const coldGrown=Buffer.from(coldStorage.read(file1));
 assert.ok(coldGrown.length>coldBytes.length&&coldGrown.subarray(0,coldBytes.length).equals(coldBytes));
 parseConfirmedJournal(coldGrown,sessionId);
 coldStorage.close();
 const plain=SessionManager.open(file1,undefined,f.project);
 assert.equal(plain.getSessionId(),sessionId);
 assert.equal(plain.getSessionFile(),file1);
});

test('malformed journal adapters throw without filesystem fallback and custody stays contained',native,async t=>{
 const f=await fixture(t);
 const jsonlUnder=async dir=>{
  const found=[];
  const walk=async current=>{for(const entry of await fs.readdir(current,{withFileTypes:true})){const child=path.join(current,entry.name);if(entry.isDirectory())await walk(child);else if(entry.name.endsWith('.jsonl'))found.push(child);}};
  await walk(dir);return found;
 };
 assert.throws(()=>SessionManager.create(f.project,f.directory.directory,undefined,{read(){},write(){}}),TypeError);
 assert.deepEqual(await jsonlUnder(path.join(f.agentDir,'sessions')),[]);
 assert.equal(f.storage.read(path.join(f.directory.directory,'missing.jsonl')),undefined);
 assert.throws(()=>f.storage.write(path.join(f.root,'escape.jsonl'),'x'),{code:'PI_JOURNAL_UNVERIFIED'});
 assert.throws(()=>f.storage.append(path.join(f.agentDir,'..','escape.jsonl'),'x'),{code:'PI_JOURNAL_UNVERIFIED'});
});
