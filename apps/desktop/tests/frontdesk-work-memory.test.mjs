import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {openTestController} from './project-storage.fixture.mjs';
import {createProviderHistoryReader} from '../src/agents/managed/provider-history.mjs';

test('project Frontdesk reviews a frozen provider snapshot, handles duplicate/old confirmations, and recalls unchanged evidence after reopen',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'nozeli-work-memory-'));
 const contentRoot=path.join(root,'project'),runtimeRoot=path.join(root,'runtime'),sourceRoot=path.join(root,'provider');
 const options={contentRoot,runtimeRoot};
 const controller=await openTestController(options);
 let current=controller;
 t.after(async()=>{await current.stop();await fs.rm(root,{recursive:true,force:true});});
 await fs.mkdir(sourceRoot);
 const file=path.join(sourceRoot,'one.jsonl'),fact='Review design Δ 😀';
 const header={type:'session',version:3,cwd:controller.store.content,id:randomUUID(),timestamp:'2026-01-01T00:00:00Z'};
 const user={type:'message',id:'00000001',parentId:null,timestamp:header.timestamp,message:{role:'user',content:[{type:'text',text:fact}]}};
 const assistant={type:'message',id:'00000002',parentId:user.id,timestamp:header.timestamp,message:{role:'assistant',content:[{type:'text',text:'Pending verification'}]}};
 const rows=[header,user,assistant];
 await fs.writeFile(file,rows.map(row=>JSON.stringify(row)).join('\n')+'\n');
 const history=createProviderHistoryReader({projectRoot:controller.store.content,providerRoots:{pi:sourceRoot}});
 t.after(()=>history.close());controller.providerHistory=history;
 const run=async(c,target='frontdesk',selectedMemorySources)=>{const job={id:randomUUID(),type:selectedMemorySources?'frontdesk-memory':'front',target,selectedMemorySources};c.current.set(target,job);return (action,args={})=>c.handleTool(target,{tool:'nozeli_frontdesk_work_memory',arguments:{action,...args}});};
 const search=(await history.search({provider:'pi',query:fact})).items[0];
 const ordinary=await run(controller);
 assert.equal((await ordinary('prepare',{source:search.source})).error.code,'MEMORY_STORE_REQUIRED');
 const frozen=await history.freeze(search.source);
 const ask=await run(controller,'frontdesk',[frozen]);
 const prepared=await ask('prepare'),id=prepared.id;
 const proposal={id,title:'Review design',summary:'Decision shared, verification pending [0].',citations:[0]};
 await assert.rejects(ask('propose',proposal),{code:'INVALID_PAYLOAD'});
 assert.equal((await ask('read',{id,record:0})).record.text,fact);
 assert.equal((await ask('propose',proposal)).status,'pending');
 const recallPending=await run(controller);
 assert.deepEqual((await recallPending('search')).items,[]);
 assert.equal((await recallPending('read',{id})).status,'not_found');
 const list=await controller.frontdeskMemoryList();assert.equal(list.items[0].id,id);
 assert.equal((await (await run(controller,'frontdesk',[frozen]))('prepare')).status,'pending');
 await assert.rejects(controller.adoptFrontdeskMemory({id,revision:2,summary:'wrong'}),{code:'INVALID_PAYLOAD'});
 const payload={id,revision:1,summary:'Reviewed; verify independently [0].'};
 const receipt=await controller.adoptFrontdeskMemory(payload);
 assert.deepEqual(await controller.adoptFrontdeskMemory(payload),receipt);
 assert.equal(controller.store.state.works.length,0);
 assert(!controller.snapshot().frontdeskWorkMemory);
 await fs.unlink(file);
 controller.current.clear();await controller.stop();
 current=await openTestController(options);
 const recall=await run(current);
 assert.deepEqual((await recall('search',{query:'Review design'})).items.map(r=>r.id),[id]);
 const summary=await recall('read',{id});assert.equal(summary.record.text,payload.summary);assert.deepEqual(summary.citations,[0]);
 const evidence=await recall('read',{id,record:summary.citations[0]});assert.equal(evidence.record.text,fact);assert.equal(evidence.evidenceDigest,summary.evidenceDigest);
 const other=await run(current,'orchestrator');
 assert.deepEqual((await other('search',{query:'Review design'})).items,[]);
 assert.equal((await other('read',{id})).status,'not_found');
 await assert.rejects(other('prepare'),{code:'FRONTDESK_READ_FORBIDDEN'});
 current.current.clear();assert.equal(current.store.state.jobs.length,0);
});
